"""Write the SEO page inventory and keyword map (Markdown) from the real
pages and _tools/seo.json.

Usage (from website/):
    python _tools/seo_report.py ../docs/seo
writes page-inventory.md and keyword-map.md into that folder.
"""
import html
import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent
CFG = json.loads((Path(__file__).resolve().parent / "seo.json").read_text(encoding="utf-8"))
BASE = CFG["site"]
PAGES = CFG["pages"]


class P(HTMLParser):
    def __init__(self):
        super().__init__()
        self.hrefs, self.words, self.skip, self.body, self.h1 = [], [], 0, False, []
        self.in_h1 = False

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "body":
            self.body = True
        if tag in ("script", "style"):
            self.skip += 1
        if tag == "h1":
            self.in_h1 = True
            self.h1.append("")
        if tag == "a" and a.get("href"):
            self.hrefs.append(a["href"])

    def handle_endtag(self, tag):
        if tag in ("script", "style"):
            self.skip -= 1
        if tag == "h1":
            self.in_h1 = False

    def handle_data(self, d):
        if self.in_h1:
            self.h1[-1] += d
        if self.body and not self.skip:
            self.words += d.split()


def target_of(page, href):
    if href.startswith(BASE):
        href = href[len(BASE):] or "/"
    elif re.match(r"^[a-z]+:", href) or href.startswith("//") or href.startswith("#"):
        return None
    path = href.split("#")[0]
    if not path:
        return None
    if path.startswith("/"):
        t = path.lstrip("/")
    else:
        t = (Path(page).parent / path).as_posix()
    if t == "" or t.endswith("/"):
        t += "index.html"
    return t if t in PAGES else None


def main_text_words(s):
    m = s[s.index("<main"):s.index("</main>")] if "<main" in s else s
    m = re.sub(r"<!-- (related|home-guides):start.*?:end -->", "", m, flags=re.S)
    p = P()
    p.body = True
    p.feed(m)
    return p.words


def collect():
    data, links_in = {}, {k: set() for k in PAGES}
    for page in PAGES:
        s = (SITE / page).read_text(encoding="utf-8")
        h = s[:s.index("</head>")]
        p = P()
        p.feed(s)
        out = {t for t in (target_of(page, x) for x in p.hrefs) if t and t != page}
        for t in out:
            links_in[t].add(page)
        data[page] = {
            "title": html.unescape((re.search(r"<title>(.*?)</title>", h) or [None, ""])[1]),
            "description": html.unescape((re.search(r'<meta name="description" content="([^"]*)"', h) or [None, ""])[1]),
            "robots": (re.search(r'<meta name="robots" content="([^"]*)"', h) or [None, ""])[1],
            "canonical": (re.search(r'<link rel="canonical" href="([^"]*)"', h) or [None, "—"])[1],
            "hreflang": ", ".join(re.findall(r'hreflang="([^"]*)" href=', h)) or "—",
            "h1": " ".join(" ".join(p.h1).split()) if len(p.h1) == 1 else f"{len(p.h1)} H1s (noindex flow)",
            "words_main": len(main_text_words(s)),
            "out": len(out),
        }
    for page in data:
        data[page]["in"] = len(links_in[page])
    return data


def cell(s):
    return str(s).replace("|", "\\|")


def inventory(data):
    rows = ["# Page inventory (generated)", "",
            "Generated by `website/_tools/seo_report.py` from the pages and `website/_tools/seo.json`. "
            "Re-run it after changing pages; do not edit by hand.", "",
            "- **Words**: words in `<main>` (header, footer and the generated related-guides block excluded).",
            "- **Links in / out**: number of distinct site pages linking to / linked from the page.", "",
            "| File | URL | Lang | Indexable | Title | Description | H1 | Canonical | hreflang | Words | Links in | Links out |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for page, d in data.items():
        p = PAGES[page]
        url = p.get("url", "—")
        rows.append("| " + " | ".join(cell(x) for x in [
            page, url, p["lang"] + (" (rtl)" if p["lang"] == "ar" else ""), "yes" if p.get("index") else "no (" + d["robots"] + ")",
            f'{d["title"]} ({len(d["title"])})', f'{d["description"]} ({len(d["description"])})', d["h1"],
            d["canonical"], d["hreflang"], d["words_main"], d["in"], d["out"]]) + " |")
    total = sum(1 for p in PAGES.values() if p.get("index"))
    rows += ["", f"Indexable pages: **{total}** (all in `sitemap.xml`). Noindex: **{len(PAGES) - total}**."]
    return "\n".join(rows) + "\n"


CLUSTER = {
    "index.html": "(3) brand-like + core", "fr/index.html": "(5) French", "ar/index.html": "(4) Arabic",
    "scanned-pdf-to-word.html": "(1) scanned / OCR", "how-to-convert-pdf-to-word.html": "(2) how-to questions",
    "pdf-to-word-alternative-to-ilovepdf.html": "(6) iLovePDF",
}


def keyword_map():
    rows = ["# Keyword map (generated)", "",
            "One primary keyword per indexable page, no two pages share a primary (checked by "
            "`website/_tests/test_seo.py`). Source: `website/_tools/seo.json`; regenerate with "
            "`python _tools/seo_report.py ../docs/seo`.", "",
            "Search Console clusters: (1) scanned pdf to word / scan to word, (2) how to convert pdf to word questions, "
            "(3) \"pdf2word\" brand-like, (4) Arabic, (5) French, (6) ilovepdf pdf to word.", "",
            "| Page | Cluster | Primary keyword | Secondary keywords | Title |", "|---|---|---|---|---|"]
    for page, p in PAGES.items():
        if not p.get("index"):
            continue
        rows.append("| " + " | ".join(cell(x) for x in [
            p["url"], CLUSTER.get(page, "supporting"), p["primary"], ", ".join(p["secondary"]) or "—", p["title"]]) + " |")
    rows += ["", "Notes:",
             "- \"pdf2word\" (brand-like, 123 impressions) is a secondary keyword of the home page only; the about page targets the brand \"pdf2wordly\".",
             "- The Arabic home targets the spellings people type (\"الى\", \"بي دي اف\"); the page itself uses correct Modern Standard Arabic (\"إلى\"). Google matches both.",
             "- The French home targets \"convertir pdf en word en ligne\" (position 9.5) as primary and the \"gratuit\" variant (33) as secondary.",
             "- Legal / help pages target brand + topic only, so they never compete with the guides."]
    return "\n".join(rows) + "\n"


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else SITE.parent / "docs" / "seo"
    out.mkdir(parents=True, exist_ok=True)
    (out / "page-inventory.md").write_text(inventory(collect()), encoding="utf-8", newline="\n")
    (out / "keyword-map.md").write_text(keyword_map(), encoding="utf-8", newline="\n")
    print("written:", out / "page-inventory.md", out / "keyword-map.md")


if __name__ == "__main__":
    main()
